#!/usr/bin/env node
/**
 * Prepare android/ for Android Studio (SDK path, cap sync, IDE hints).
 *   npm run android:studio
 */
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";

const root = join(import.meta.dirname, "..");
const androidDir = join(root, "android");
const localProps = join(androidDir, "local.properties");
const ideaDir = join(androidDir, ".idea");

function ok(label, detail = "") {
  console.log(`  ✓ ${label}${detail ? ` — ${detail}` : ""}`);
}

function warn(label, detail = "") {
  console.warn(`  ! ${label}${detail ? ` — ${detail}` : ""}`);
}

function fail(label, detail = "") {
  console.error(`  ✗ ${label}${detail ? ` — ${detail}` : ""}`);
}

function resolveAndroidSdk() {
  if (process.env.ANDROID_HOME?.trim()) return process.env.ANDROID_HOME.trim();
  if (process.env.ANDROID_SDK_ROOT?.trim()) return process.env.ANDROID_SDK_ROOT.trim();

  const candidates = [
    join(homedir(), "AppData", "Local", "Android", "Sdk"),
    join(homedir(), "Library", "Android", "sdk"),
    join(homedir(), "Android", "Sdk"),
  ];
  return candidates.find((path) => existsSync(path)) ?? null;
}

function resolveJavaHome() {
  if (process.env.JAVA_HOME?.trim()) return process.env.JAVA_HOME.trim();

  if (process.platform === "win32") {
    const studioJbr = "C:\\Program Files\\Android\\Android Studio\\jbr";
    if (existsSync(join(studioJbr, "bin", "java.exe"))) return studioJbr;

    const localStudio = join(
      process.env.LOCALAPPDATA ?? "",
      "Programs",
      "Android Studio",
      "jbr",
    );
    if (existsSync(join(localStudio, "bin", "java.exe"))) return localStudio;

    const adoptiumRoot = "C:\\Program Files\\Eclipse Adoptium";
    if (existsSync(adoptiumRoot)) {
      const jdks = readdirSync(adoptiumRoot, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && entry.name.startsWith("jdk-"))
        .map((entry) => join(adoptiumRoot, entry.name))
        .sort()
        .reverse();
      if (jdks[0]) return jdks[0];
    }
  }

  return null;
}

function toGradlePath(path) {
  // Lint PropertyEscape: escape drive colon and backslashes for .properties files.
  return path.replace(/\\/g, "/").replace(/^([A-Za-z]):\//, "$1\\:/");
}

function writeLocalProperties(sdkPath) {
  const content = `# Generated by npm run android:studio — do not commit (see android/.gitignore)
sdk.dir=${toGradlePath(sdkPath)}
`;
  writeFileSync(localProps, content, "utf8");
}

function writeGradleXml(javaHome) {
  mkdirSync(ideaDir, { recursive: true });
  const gradleJvm = javaHome ? "jbr-21" : "jbr-21";
  const gradleXml = join(ideaDir, "gradle.xml");
  if (existsSync(gradleXml)) return;

  writeFileSync(
    gradleXml,
    `<?xml version="1.0" encoding="UTF-8"?>
<project version="4">
  <component name="GradleMigrationSettings" migrationVersion="1" />
  <component name="GradleSettings">
    <option name="linkedExternalProjectsSettings">
      <GradleProjectSettings>
        <option name="testRunner" value="CHOOSE_PER_TEST" />
        <option name="externalProjectPath" value="$PROJECT_DIR$" />
        <option name="gradleJvm" value="${gradleJvm}" />
        <option name="modules">
          <set>
            <option value="$PROJECT_DIR$" />
            <option value="$PROJECT_DIR$/app" />
          </set>
        </option>
      </GradleProjectSettings>
    </option>
  </component>
</project>
`,
    "utf8",
  );
}

console.log("\nSyNexus — Android Studio setup\n");

let errors = 0;

const sdk = resolveAndroidSdk();
if (sdk) {
  writeLocalProperties(sdk);
  ok("local.properties", sdk);
} else {
  fail("Android SDK not found", "Install SDK in Android Studio → Settings → Android SDK");
  errors++;
}

const javaHome = resolveJavaHome();
if (javaHome) ok("Java", javaHome);
else warn("JAVA_HOME not detected", "Android Studio bundled JBR is usually enough");

writeGradleXml(javaHome);
ok(".idea/gradle.xml", existsSync(join(ideaDir, "gradle.xml")) ? "ready" : "skipped");

const sync = spawnSync("npx cap sync android", {
  cwd: root,
  stdio: "inherit",
  shell: true,
  env: {
    ...process.env,
    ...(javaHome ? { JAVA_HOME: javaHome } : {}),
    ...(sdk ? { ANDROID_HOME: sdk, ANDROID_SDK_ROOT: sdk } : {}),
  },
});

if (sync.status === 0) ok("cap sync android");
else {
  fail("cap sync android failed");
  errors++;
}

const pluginsDir = join(androidDir, "capacitor-cordova-android-plugins");
if (existsSync(pluginsDir)) ok("capacitor-cordova-android-plugins");
else {
  fail("capacitor-cordova-android-plugins missing", "cap sync should create this");
  errors++;
}

console.log("\nOpen in Android Studio:");
console.log("  npx cap open android");
console.log("  (open the android/ folder, not the repo root)\n");

if (errors > 0) process.exit(1);
console.log("Android Studio should sync cleanly.\n");
