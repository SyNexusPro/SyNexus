#!/usr/bin/env node
/**
 * One-time Play upload keystore for Synexus Android.
 * Creates android/upload-keystore.jks + android/keystore.properties (both gitignored).
 *
 *   node scripts/setup-android-keystore.mjs
 */
import { randomBytes } from "node:crypto";
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const androidDir = join(root, "android");
const keystoreFile = join(androidDir, "upload-keystore.jks");
const propsFile = join(androidDir, "keystore.properties");
const backupFile = join(androidDir, "KEYSTORE-BACKUP.txt");
const alias = "synexus-upload";

function resolveKeytool() {
  if (process.env.JAVA_HOME) {
    const candidate = join(process.env.JAVA_HOME, "bin", process.platform === "win32" ? "keytool.exe" : "keytool");
    if (existsSync(candidate)) return candidate;
  }
  if (process.platform === "win32") {
    const adoptiumRoot = "C:\\Program Files\\Eclipse Adoptium";
    if (existsSync(adoptiumRoot)) {
      for (const name of readdirSync(adoptiumRoot).sort().reverse()) {
        if (!name.startsWith("jdk-21")) continue;
        const candidate = join(adoptiumRoot, name, "bin", "keytool.exe");
        if (existsSync(candidate)) return candidate;
      }
    }
  }
  return "keytool";
}

function randomPassword() {
  return randomBytes(18).toString("base64url");
}

if (existsSync(keystoreFile) || existsSync(propsFile)) {
  console.error("Keystore already exists. Delete upload-keystore.jks and keystore.properties to recreate.");
  process.exit(1);
}

const storePassword = randomPassword();
const keyPassword = storePassword;
const keytool = resolveKeytool();
const dname = "CN=SyNexus, OU=Mobile, O=SyNexus Pro, L=United States, ST=United States, C=US";

console.log("Creating upload keystore…");

const result = spawnSync(
  keytool,
  [
    "-genkeypair",
    "-v",
    "-keystore",
    keystoreFile,
    "-alias",
    alias,
    "-keyalg",
    "RSA",
    "-keysize",
    "2048",
    "-validity",
    "10000",
    "-storepass",
    storePassword,
    "-keypass",
    keyPassword,
    "-dname",
    dname,
  ],
  { stdio: "inherit" },
);

if (result.status !== 0) {
  process.exit(result.status ?? 1);
}

const props = `# Generated by scripts/setup-android-keystore.mjs — do not commit
storePassword=${storePassword}
keyPassword=${keyPassword}
keyAlias=${alias}
storeFile=upload-keystore.jks
`;

writeFileSync(propsFile, props, "utf8");

const backup = `SyNexus Android upload keystore backup
Generated: ${new Date().toISOString()}
Machine: ${homedir()}

Keystore file: android/upload-keystore.jks
Alias: ${alias}
Store password: ${storePassword}
Key password: ${keyPassword}

IMPORTANT:
1. Copy this file to a password manager or offline backup, then delete it from the repo folder.
2. If you lose the keystore or passwords, you cannot update the app on Google Play with the same package.
3. Never commit upload-keystore.jks or keystore.properties to git.
`;

writeFileSync(backupFile, backup, "utf8");

console.log("\n✓ Upload keystore created.");
console.log(`  ${keystoreFile}`);
console.log(`  ${propsFile}`);
console.log(`\n⚠ Passwords saved to: ${backupFile}`);
console.log("  Back that up offline, then delete KEYSTORE-BACKUP.txt from this folder.\n");
